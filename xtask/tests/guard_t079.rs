//! T-079 guards (test author). Both pass on the base (`ee9b130`) and must pass after T-079.
//!
//! 1. Interface (3) and the Guard of "Acceptance criteria": every Linux test name of the base
//!    still exists at the head. The criterion names `cargo test --workspace -- --list`; this
//!    file does not run it (it builds the whole workspace inside a test, needs Linux to list
//!    Linux names, and on Windows `kiln-workspace` does not compile, so the guard would fail
//!    `xtask` there — AC-5). Instead it computes the same set from the sources, as `no-skip`
//!    does, with `syn` (a dependency of `xtask`): every fn carrying a `#[test]` attribute (also
//!    path forms such as `tokio::test`) in a `.rs` file under `crates/`, `apps/`, `xtask/`
//!    (`target`, `.git`, `.worktrees` and `xtask/fixtures` skipped, as `no-skip` skips them),
//!    whose own `cfg`s, those of the inline `mod`s around it, the file's inner `#![cfg]` and the
//!    `mod name;` declaration of its file hold on Linux (`test`, `unix`, `target_os = "linux"`,
//!    `target_family = "unix"` true; `windows` and other `target_os`/`target_family` values
//!    false; `not`/`all`/`any` evaluated; any other predicate counts as false, so it can only
//!    make a name absent, never present). A name is `<file>::<inline mod path>::<fn>`, the
//!    registry's `file`/`item` convention: for a given file this fixes the name `cargo test`
//!    prints and the test binary it is in. Doc tests are not included: their names carry line
//!    numbers. Tests generated by a macro are not seen (on the base none is: every `#[test]`
//!    in the tracked sources outside `xtask/fixtures` is an item `syn` reads).
//!
//!    The base's set is pinned in this file ([`BASE`], at the end) and its size in
//!    [`BASE_COUNT`]: the list was produced on the base by this file's own scanner and
//!    cross-checked against `cargo test -p xtask -- --list` (see the task log); an emptied or
//!    truncated list fails `base_list_is_the_pinned_measurement`. No network and no second
//!    checkout: CI checks out with `fetch-depth: 1`, so the base commit is not readable there.
//!
//! 2. AC-2 (ruling Q-5 A: a guard): the four tests fixed portably in Interface (1) carry no
//!    platform cfg: the set of `cfg`/`cfg_attr` attributes with a platform predicate (`unix`,
//!    `windows`, any `target_*` key) on the fn, inside its body at any depth, on the inline mods
//!    around it, on the file (`#![cfg]`) and on the file's `mod` declaration is empty. A
//!    `cfg!(…)` expression is not an attribute and is allowed (Interface (1): the expected
//!    errno "chosen in the test by platform; no `cfg` on the test").
//!
//! Only `std::fs` and `syn` are used: the same on Linux, macOS and Windows; paths are compared
//! as `/`-separated repository-relative strings. No process is spawned.
#![cfg(test)]

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

use syn::visit::{self, Visit};

// ---- repository files ---------------------------------------------------------------------

/// The repository root (the parent of the `xtask` package).
fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask has a parent directory")
        .to_path_buf()
}

/// `path` relative to `root`, `/`-separated.
fn rel(root: &Path, path: &Path) -> String {
    let r = path
        .strip_prefix(root)
        .unwrap_or_else(|_| panic!("{} is not under {}", path.display(), root.display()));
    r.components()
        .map(|c| c.as_os_str().to_string_lossy().into_owned())
        .collect::<Vec<_>>()
        .join("/")
}

/// Every `.rs` file under `crates/`, `apps/`, `xtask/` (as `no-skip` walks them), relative.
fn rust_files(root: &Path) -> Vec<String> {
    let mut out = Vec::new();
    let mut stack: Vec<PathBuf> = ["crates", "apps", "xtask"]
        .iter()
        .map(|d| root.join(d))
        .collect();
    while let Some(d) = stack.pop() {
        if !d.is_dir() {
            continue;
        }
        let entries = std::fs::read_dir(&d)
            .unwrap_or_else(|e| panic!("precondition: cannot read {}: {e}", d.display()));
        for entry in entries {
            let path = entry.expect("directory entry").path();
            let name = path
                .file_name()
                .and_then(|n| n.to_str())
                .unwrap_or_default()
                .to_owned();
            if path.is_dir() {
                if !matches!(name.as_str(), "target" | ".git" | ".worktrees")
                    && rel(root, &path) != "xtask/fixtures"
                {
                    stack.push(path);
                }
            } else if name.ends_with(".rs") {
                out.push(rel(root, &path));
            }
        }
    }
    out.sort();
    out
}

fn parse(root: &Path, file: &str) -> syn::File {
    let p = root.join(file);
    let text = std::fs::read_to_string(&p)
        .unwrap_or_else(|e| panic!("precondition: cannot read {}: {e}", p.display()));
    syn::parse_file(&text).unwrap_or_else(|e| panic!("precondition: {file} does not parse: {e}"))
}

// ---- cfg predicates -----------------------------------------------------------------------

/// The predicate of a `#[cfg(…)]`, or of a `#[cfg_attr(…, …)]` (its first argument).
fn cfg_predicate(a: &syn::Attribute) -> Option<syn::Meta> {
    let is_cfg = a.path().is_ident("cfg");
    if !is_cfg && !a.path().is_ident("cfg_attr") {
        return None;
    }
    let args = a
        .parse_args_with(syn::punctuated::Punctuated::<syn::Meta, syn::Token![,]>::parse_terminated)
        .unwrap_or_else(|e| panic!("precondition: unreadable cfg attribute: {e}"));
    args.into_iter().next()
}

fn str_value(nv: &syn::MetaNameValue) -> Option<String> {
    match &nv.value {
        syn::Expr::Lit(syn::ExprLit {
            lit: syn::Lit::Str(s),
            ..
        }) => Some(s.value()),
        _ => None,
    }
}

fn nested(l: &syn::MetaList) -> Vec<syn::Meta> {
    l.parse_args_with(syn::punctuated::Punctuated::<syn::Meta, syn::Token![,]>::parse_terminated)
        .unwrap_or_else(|e| panic!("precondition: unreadable cfg predicate: {e}"))
        .into_iter()
        .collect()
}

/// Whether a cfg predicate holds in a Linux test build (unknown predicates: false).
fn holds_on_linux(m: &syn::Meta) -> bool {
    match m {
        syn::Meta::Path(p) => p.is_ident("test") || p.is_ident("unix"),
        syn::Meta::NameValue(nv) => {
            let v = str_value(nv);
            if nv.path.is_ident("target_os") {
                v.as_deref() == Some("linux")
            } else if nv.path.is_ident("target_family") {
                v.as_deref() == Some("unix")
            } else {
                false
            }
        }
        syn::Meta::List(l) => {
            let args = nested(l);
            if l.path.is_ident("not") {
                args.len() == 1 && !holds_on_linux(&args[0])
            } else if l.path.is_ident("all") {
                args.iter().all(holds_on_linux)
            } else if l.path.is_ident("any") {
                args.iter().any(holds_on_linux)
            } else {
                false
            }
        }
    }
}

/// Whether a cfg predicate names a platform (`unix`, `windows`, a `target_*` key).
fn is_platform(m: &syn::Meta) -> bool {
    let named = |p: &syn::Path| {
        p.is_ident("unix")
            || p.is_ident("windows")
            || p.get_ident()
                .is_some_and(|i| i.to_string().starts_with("target_"))
    };
    match m {
        syn::Meta::Path(p) => named(p),
        syn::Meta::NameValue(nv) => named(&nv.path),
        syn::Meta::List(l) => named(&l.path) || nested(l).iter().any(is_platform),
    }
}

/// Whether every `#[cfg]` among `attrs` holds on Linux (`cfg_attr` does not remove an item).
fn kept_on_linux(attrs: &[syn::Attribute]) -> bool {
    attrs
        .iter()
        .filter(|a| a.path().is_ident("cfg"))
        .filter_map(cfg_predicate)
        .all(|m| holds_on_linux(&m))
}

/// The platform cfg/cfg_attr attributes among `attrs`, as text (for the failure message).
fn platform_cfgs(attrs: &[syn::Attribute], at: &str, out: &mut Vec<String>) {
    for a in attrs {
        if let Some(m) = cfg_predicate(a)
            && is_platform(&m)
        {
            let text = quote_attr(a);
            out.push(format!("{at}: {text}"));
        }
    }
}

/// A cfg attribute as text, for the failure message (without the `quote` crate).
fn quote_attr(a: &syn::Attribute) -> String {
    match &a.meta {
        syn::Meta::List(l) if a.path().is_ident("cfg") => format!("#[cfg({})]", l.tokens),
        syn::Meta::List(l) => format!("#[cfg_attr({})]", l.tokens),
        _ => "#[cfg]".to_owned(),
    }
}

// ---- out-of-line module declarations ------------------------------------------------------

/// The files a `mod name;` (or `#[path = …] mod name;`) in `file` may load (both directory
/// conventions; an over-approximation only ever removes names, which fails loudly).
fn module_candidates(file: &str, m: &syn::ItemMod) -> Vec<String> {
    let dir = match file.rfind('/') {
        Some(i) => &file[..i],
        None => "",
    };
    let join = |d: &str, f: &str| {
        if d.is_empty() {
            f.to_owned()
        } else {
            format!("{d}/{f}")
        }
    };
    for a in &m.attrs {
        if a.path().is_ident("path")
            && let syn::Meta::NameValue(nv) = &a.meta
            && let Some(p) = str_value(nv)
        {
            return vec![join(dir, &p.replace('\\', "/"))];
        }
    }
    let name = m.ident.to_string();
    let stem = file
        .rsplit('/')
        .next()
        .unwrap_or_default()
        .trim_end_matches(".rs");
    let own = join(dir, stem);
    vec![
        join(dir, &format!("{name}.rs")),
        join(dir, &format!("{name}/mod.rs")),
        join(&own, &format!("{name}.rs")),
        join(&own, &format!("{name}/mod.rs")),
    ]
}

/// For every file, the attributes of the `mod name;` declarations that may load it.
fn declarations(root: &Path, files: &[String]) -> BTreeMap<String, Vec<syn::Attribute>> {
    let mut out: BTreeMap<String, Vec<syn::Attribute>> = BTreeMap::new();
    for f in files {
        for item in parse(root, f).items {
            if let syn::Item::Mod(m) = item
                && m.content.is_none()
            {
                for c in module_candidates(f, &m) {
                    out.entry(c).or_default().extend(m.attrs.iter().cloned());
                }
            }
        }
    }
    out
}

// ---- the Linux test names -----------------------------------------------------------------

fn is_test_attr(a: &syn::Attribute) -> bool {
    a.path().segments.last().is_some_and(|s| s.ident == "test")
}

fn collect_tests(file: &str, items: &[syn::Item], prefix: &str, out: &mut BTreeSet<String>) {
    for item in items {
        match item {
            syn::Item::Fn(f) if f.attrs.iter().any(is_test_attr) && kept_on_linux(&f.attrs) => {
                out.insert(format!("{file}::{prefix}{}", f.sig.ident));
            }
            syn::Item::Mod(m) if kept_on_linux(&m.attrs) => {
                if let Some((_, inner)) = &m.content {
                    collect_tests(file, inner, &format!("{prefix}{}::", m.ident), out);
                }
            }
            _ => {}
        }
    }
}

/// The Linux test names of the tree at `root` (see the file comment).
fn linux_test_names(root: &Path) -> BTreeSet<String> {
    let files = rust_files(root);
    let decls = declarations(root, &files);
    let mut out = BTreeSet::new();
    for f in &files {
        if decls.get(f).is_some_and(|a| !kept_on_linux(a)) {
            continue;
        }
        let parsed = parse(root, f);
        if !kept_on_linux(&parsed.attrs) {
            continue;
        }
        collect_tests(f, &parsed.items, "", &mut out);
    }
    out
}

