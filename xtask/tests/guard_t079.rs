// ---- AC-2: the four portable fixes carry no platform cfg ----------------------------------

/// Every attribute inside a fn body, at any depth (items, statements, expressions, closures).
struct Attrs<'s> {
    out: &'s mut Vec<String>,
}

impl<'ast> Visit<'ast> for Attrs<'_> {
    fn visit_attribute(&mut self, a: &'ast syn::Attribute) {
        platform_cfgs(std::slice::from_ref(a), "in the body", self.out);
        visit::visit_attribute(self, a);
    }
}

/// The platform cfgs bearing on test `item` (`mod::…::fn`) of `file`; panics if the fn does not
/// exist as a `#[test]` there (so the guard cannot pass on a renamed or removed test).
fn platform_cfgs_of(file: &str, item: &str) -> Vec<String> {
    let root = root();
    let files = rust_files(&root);
    assert!(
        files.iter().any(|f| f == file),
        "precondition: {file} does not exist"
    );
    let parsed = parse(&root, file);
    let mut found = Vec::new();
    let decls = declarations(&root, &files);
    if let Some(a) = decls.get(file) {
        platform_cfgs(a, "on the `mod` declaration of the file", &mut found);
    }
    platform_cfgs(&parsed.attrs, "on the file (#![…])", &mut found);
    let mut path: Vec<&str> = item.split("::").collect();
    let name = path.pop().expect("an item name");
    let mut items = &parsed.items;
    for m in &path {
        let module = items
            .iter()
            .find_map(|i| match i {
                syn::Item::Mod(x) if x.ident == m => Some(x),
                _ => None,
            })
            .unwrap_or_else(|| panic!("precondition: {file} has no inline `mod {m}`"));
        platform_cfgs(&module.attrs, &format!("on `mod {m}`"), &mut found);
        items = &module
            .content
            .as_ref()
            .unwrap_or_else(|| panic!("precondition: `mod {m}` in {file} is not inline"))
            .1;
    }
    let fns: Vec<&syn::ItemFn> = items
        .iter()
        .filter_map(|i| match i {
            syn::Item::Fn(f) if f.sig.ident == name => Some(f),
            _ => None,
        })
        .collect();
    assert_eq!(
        fns.len(),
        1,
        "precondition: {file}::{item} is not exactly one fn"
    );
    let f = fns[0];
    assert!(
        f.attrs.iter().any(is_test_attr),
        "precondition: {file}::{item} is not a #[test] fn"
    );
    platform_cfgs(&f.attrs, "on the fn", &mut found);
    Attrs { out: &mut found }.visit_block(&f.block);
    found
}

fn assert_no_platform_cfg(file: &str, item: &str) {
    let found = platform_cfgs_of(file, item);
    assert!(
        found.is_empty(),
        "{file}::{item} is one of T-079's four portable fixes and must carry no platform cfg \
         (AC-2); found:\n{}",
        found.join("\n")
    );
}

