"""Window (`kiln --script` under xvfb-run) vs headless (`kiln script`) on the same script.

usage: wincmp.py <screen WxH> <limit> <fixture-glob-prefix> [--size-headless WxH] [--no-root]
  Takes fuzz sessions already generated by fuzz.py: initial fixture `fx/fz<seed>-<si>-*` and its
  script `fx/script-fz<seed>-<si>-*/s.jsonl` (prefix e.g. `fz1-`). For each (up to <limit>):
  copies the initial fixture twice, runs the window on one and `kiln script` on the other with
  the same start path, compares stdout bytes, exit codes, files afterwards; reports stderr of the
  window and whether HOME got any file.
  --no-root: run both with the fixture as current directory and without --root.
env: KILN_BIN, KILN_WORK, XLIBS.
"""
import glob, os, re, subprocess, sys, shutil
sys.path.insert(0, os.path.dirname(__file__))
import kl

screen, limit, prefix = sys.argv[1], int(sys.argv[2]), sys.argv[3]
hsize = None
if "--size-headless" in sys.argv:
    hsize = sys.argv[sys.argv.index("--size-headless") + 1]
noroot = "--no-root" in sys.argv
XLIBS = os.environ["XLIBS"]

pairs = []
for sd in sorted(glob.glob(os.path.join(kl.WORK, "fx", f"script-{prefix}*"))):
    m = re.match(r"script-(fz\d+-\d+)-(\d+)-\d+$", os.path.basename(sd))
    if not m:
        continue
    inits = [d for d in glob.glob(os.path.join(kl.WORK, "fx", f"{m.group(1)}-{m.group(2)}-*"))
             if os.path.isdir(d)]
    if len(inits) != 1:
        continue
    pairs.append((inits[0], os.path.join(sd, "s.jsonl")))
pairs = pairs[:limit]
n = diff_out = diff_rc = diff_files = stderr_nonempty = home_files = 0
lines = 0
for init, script in pairs:
    files = [f for f in os.listdir(init)]
    path = files[0]
    w = kl.copytree(init, "winw")
    h = kl.copytree(init, "winh")
    home = kl.fresh("winhome")
    errf = w + ".stderr"
    inner = f'exec "$KILN_BIN" {"" if noroot else "--root " + w} {path} --script {script} 2>{errf}'
    env = dict(os.environ)
    env.pop("WAYLAND_DISPLAY", None)
    env.update(LD_LIBRARY_PATH=XLIBS + "/usr/lib/x86_64-linux-gnu", MESA_SHADER_CACHE_DISABLE="true", HOME=home)
    p = subprocess.run(["timeout", "300", "xvfb-run", "-a", "-s", f"-screen 0 {screen}x24", "sh", "-c", inner],
                       capture_output=True, env=env, cwd=w if noroot else None)
    argv = [kl.BIN, "script", script] + ([] if noroot else ["--root", h]) + [path]
    if hsize:
        argv += ["--size", hsize]
    q = subprocess.run(["timeout", "300"] + argv, capture_output=True, cwd=h if noroot else None)
    n += 1
    lines += q.stdout.count(b"\n")
    if p.stdout != q.stdout:
        diff_out += 1
        a, b = p.stdout.splitlines(), q.stdout.splitlines()
        i = next((i for i, (x, y) in enumerate(zip(a, b)) if x != y), min(len(a), len(b)))
        print("OUT DIFF", script, "line", i, (a[i][:300] if i < len(a) else None), "|", (b[i][:300] if i < len(b) else None))
    if p.returncode != q.returncode:
        diff_rc += 1
        print("RC DIFF", script, p.returncode, q.returncode, p.stderr[:300])
    fw = kl.read_tree(w); fh = kl.read_tree(h)
    if fw != fh:
        diff_files += 1
        print("FILES DIFF", script)
    e = open(errf, "rb").read()
    if e:
        stderr_nonempty += 1
        print("STDERR", script, e[:300])
    hf = [os.path.join(dp, f) for dp, dn, fn in os.walk(home) for f in fn]
    if hf:
        home_files += 1
        print("HOME FILES", hf[:5])
print(f"screen={screen} headless_size={hsize} noroot={noroot} scripts={n} response_lines={lines} stdout_differ={diff_out} rc_differ={diff_rc} files_differ={diff_files} window_stderr_nonempty={stderr_nonempty} home_written={home_files}")
